"""Write docs/wx/tz.js: the IANA time zone of every airport in docs/airports-us.js and every destination.

Usage: pip install timezonefinder; python3 tools/wx/timezones_wx.py
The weather outlook uses it to read and show times in each airport's local time. Re-run when airports change.
"""
import json, re
from pathlib import Path
from timezonefinder import TimezoneFinder

root = Path(__file__).resolve().parents[2]
tf = TimezoneFinder()
pts = {}
for code, alt, lat, lon in re.findall(r'\["([A-Z0-9]+)","([A-Z0-9]*)","[^"]*","[^"]*","[^"]*",(-?[\d.]+),(-?[\d.]+)\]', (root / 'docs/airports-us.js').read_text()):
    pts[code] = (float(lat), float(lon))
d = (root / 'docs/destinations.js').read_text()
for ap, lat, lon in re.findall(r'"airport": "([A-Z0-9]+)".*?"lat": (-?[\d.]+),\s*"lon": (-?[\d.]+)', d, re.S):
    pts.setdefault(ap, (float(lat), float(lon)))
zones, out = [], {}
for code, (lat, lon) in sorted(pts.items()):
    z = tf.timezone_at(lng=lon, lat=lat) or tf.closest_timezone_at(lng=lon, lat=lat)
    if not z:
        continue
    if z not in zones:
        zones.append(z)
    out[code] = zones.index(z)
src = '// Airport time zones for the WingAway weather outlook: WINGAWAY_TZ.z = zone names, .a = airport -> index.\n'
src += '// Generated by tools/wx/timezones_wx.py from airport coordinates (timezonefinder).\n'
src += 'window.WINGAWAY_TZ=' + json.dumps({'z': zones, 'a': out}, separators=(',', ':')) + ';\n'
(root / 'docs/wx/tz.js').write_text(src)
print(len(out), 'airports,', len(zones), 'zones:', zones)
