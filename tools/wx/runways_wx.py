"""Write docs/wx/runways.js: runways for the crosswind check, from FAA NASR.

Usage: python3 tools/wx/runways_wx.py /path/to/nasr   (folder with APT_BASE.csv, APT_RWY.csv, APT_RWY_END.csv)

For every airport in docs/airports-us.js: each land runway's ID, length (ft), surface and the true heading of
both ends. True headings match the NBM wind direction, which is also true. Re-run with each NASR cycle.
"""
import csv, json, re, sys
from collections import defaultdict
from pathlib import Path

nasr = Path(sys.argv[1]); root = Path(__file__).resolve().parents[2]
ids = set()
for code, alt in re.findall(r'\["([A-Z0-9]+)","([A-Z0-9]*)"', (root / 'docs/airports-us.js').read_text()):
    ids.update({code, alt, code[1:] if len(code) == 4 and code[0] == 'K' else code} - {''})
ids.update(c[1:] if len(c) == 4 and c[0] == 'K' else c for c in re.findall(r'"airport": "([A-Z0-9]+)"', (root / 'docs/destinations.js').read_text()))

var = {}
for b in csv.DictReader(open(nasr / 'APT_BASE.csv', encoding='latin-1')):
    try: v = float(b.get('MAG_VARN') or '')
    except ValueError: continue
    var[b['ARPT_ID']] = v if (b.get('MAG_HEMIS') or 'E') == 'E' else -v

rw = {}
for r in csv.DictReader(open(nasr / 'APT_RWY.csv', encoding='latin-1')):
    s = r['SURFACE_TYPE_CODE'] or ''
    if r['ARPT_ID'] in ids and s and not s.startswith('WATER'):
        try: ln = int(float(r['RWY_LEN'] or 0))
        except ValueError: continue
        rw[(r['ARPT_ID'], r['RWY_ID'])] = [r['RWY_ID'], ln, s.split('-')[0][:4]]
ends = defaultdict(dict)
for e in csv.DictReader(open(nasr / 'APT_RWY_END.csv', encoding='latin-1')):
    k = (e['ARPT_ID'], e['RWY_ID'])
    if k in rw and (e['TRUE_ALIGNMENT'] or '').strip():
        ends[k][e['RWY_END_ID']] = int(float(e['TRUE_ALIGNMENT']))
out = defaultdict(list)
for k, v in rw.items():
    e = ends.get(k, {})
    ids_ = k[1].split('/')
    hs = [e.get(i) for i in ids_] if len(ids_) == 2 else []
    if len(hs) == 2 and hs.count(None) == 1:
        h = next(x for x in hs if x is not None)
        hs = [h if x is not None else (h + 180) % 360 for x in hs]
    if len(hs) == 2 and hs == [None, None] and k[0] in var and all(re.fullmatch(r'\d{1,2}[LRC]?', i) for i in ids_):
        # No surveyed heading: runway number x 10 is magnetic; add the airport's variation for true.
        hs = [round(int(re.match(r'\d+', i).group()) * 10 + var[k[0]]) % 360 for i in ids_]
    if len(hs) == 2 and None not in hs:
        out[k[0]].append(v + hs)  # heading of the end named first in the ID, then the second
for a in out: out[a].sort(key=lambda x: -x[1])
src = '// Runways for the WingAway weather outlook: [id, length ft, surface, true heading end 1, end 2].\n'
src += '// Source: FAA NASR (APT_RWY, APT_RWY_END). Generated by tools/wx/runways_wx.py.\n'
src += 'window.WINGAWAY_RWYS=' + json.dumps(out, separators=(',', ':')) + ';\n'
(root / 'docs/wx').mkdir(exist_ok=True); (root / 'docs/wx/runways.js').write_text(src)
print(f'{len(out)} airports with runway headings', file=sys.stderr)
